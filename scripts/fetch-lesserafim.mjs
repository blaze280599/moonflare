// Builds lib/photos/lesserafim.js: the photo URL for every LE SSERAFIM card, plus album covers.
// Run with `npm run photos:lesserafim` after a comeback, then add the era to ERAS in lib/cards.js.
//
// Photos come from the member gallery pages on the K-pop fandom wiki (kpop.fandom.com), read
// through its MediaWiki API. No images are downloaded or committed: the app hotlinks the wiki's
// CDN, which crops each photo to card shape server-side. The CDN blocks non-browser clients, so
// this script only reads the API, never the images.

import { writeFile } from 'node:fs/promises';

const API = 'https://kpop.fandom.com/api.php';
const OUT = new URL('../lib/photos/lesserafim.js', import.meta.url);

// Card member code → gallery page.
const MEMBERS = {
  CW: 'Kim Chaewon (LE SSERAFIM)/Gallery',
  SK: 'Sakura (LE SSERAFIM)/Gallery',
  YJ: 'Huh Yunjin/Gallery',
  KZ: 'Kazuha/Gallery',
  EC: 'Hong Eunchae/Gallery'
};
const GROUP_GALLERY = 'LE SSERAFIM/Gallery';

// Era code → the album page that gallery captions link to, and the album's cover file.
const ERAS = {
  FL: { page: 'Fearless (LE SSERAFIM)', cover: 'LE SSERAFIM Fearless digital album cover.png' },
  AF: { page: 'Antifragile', cover: 'LE SSERAFIM Antifragile digital album cover.png' },
  UF: { page: 'Unforgiven', cover: 'LE SSERAFIM Unforgiven digital album cover.png' },
  EZ: { page: 'Easy (LE SSERAFIM)', cover: 'LE SSERAFIM Easy digital album cover.png' },
  CZ: { page: 'Crazy (LE SSERAFIM)', cover: 'LE SSERAFIM Crazy digital cover.png' },
  HT: { page: 'Hot (LE SSERAFIM)', cover: 'LE SSERAFIM Hot digital album cover.png' },
  PF: { page: 'Pureflow Pt.1', cover: 'LE SSERAFIM Pureflow Pt 1 digital album cover.png' }
};

// Member cards per era, in this order: album PC, selfie PC, POB, lucky draw.
const PER_MEMBER = 4;

async function api(params) {
  const url = `${API}?${new URLSearchParams({ format: 'json', ...params })}`;
  const res = await fetch(url, { headers: { 'User-Agent': 'MoonflarePhotocardClub/1.0 (personal fan project)' } });
  if (!res.ok) throw new Error(`${res.status} for ${url}`);
  return res.json();
}

// Gallery lines look like `File name.png|''[[Album page|Label]]'' (3)`. Returns { albumPage: [file, ...] }.
async function galleryByAlbum(page) {
  const { parse } = await api({ action: 'parse', page, prop: 'wikitext' });
  const byAlbum = {};
  for (const line of parse.wikitext['*'].split('\n')) {
    const m = line.match(/^([^|]+\.(?:png|jpe?g|webp))\|''\[\[([^\]|]+)/i);
    if (m) (byAlbum[m[2]] ??= []).push(m[1].trim());
  }
  return byAlbum;
}

// Spreads picks across the shoot, so one card isn't a near-copy of the next.
const spread = (files, n) => Array.from({ length: Math.min(n, files.length) }, (_, i) => files[Math.floor((i * files.length) / n)]);

// File name → CDN URL cropped to w×h. "smart" crops around the subject.
async function cdnUrls(files, w, h) {
  const out = {};
  for (let i = 0; i < files.length; i += 50) {
    const titles = files.slice(i, i + 50).map(f => `File:${f}`).join('|');
    const { query } = await api({ action: 'query', titles, prop: 'imageinfo', iiprop: 'url' });
    const renamed = Object.fromEntries((query.normalized ?? []).map(n => [n.to, n.from]));
    for (const p of Object.values(query.pages)) {
      if (!p.imageinfo) continue;
      const [base, cb] = p.imageinfo[0].url.split('?');
      const file = (renamed[p.title] ?? p.title).replace(/^File:/, '');
      out[file] = `${base}/smart/width/${w}/height/${h}?${cb}`;
    }
  }
  return out;
}

const galleries = {};
for (const [code, page] of Object.entries({ ...MEMBERS, GRP: GROUP_GALLERY })) galleries[code] = await galleryByAlbum(page);

const picks = {}; // era → member code → files
for (const [era, { page }] of Object.entries(ERAS)) {
  picks[era] = {};
  for (const code of Object.keys(MEMBERS)) {
    const files = galleries[code][page] ?? [];
    if (files.length < PER_MEMBER) throw new Error(`${code} has ${files.length} ${page} photos, need ${PER_MEMBER}`);
    picks[era][code] = spread(files, PER_MEMBER);
  }
  const group = galleries.GRP[page] ?? [];
  if (!group.length) throw new Error(`no ${page} group photos`);
  picks[era].GRP = [group[0]];
}

const cardFiles = Object.values(picks).flatMap(e => Object.values(e).flat());
const cardUrls = await cdnUrls(cardFiles, 630, 880);
const coverUrls = await cdnUrls(Object.values(ERAS).map(e => e.cover), 600, 600);

const photos = {};
for (const [era, members] of Object.entries(picks)) {
  const cover = coverUrls[ERAS[era].cover];
  if (!cover) throw new Error(`missing cover for ${era}`);
  photos[era] = { cover, cards: {} };
  for (const [code, files] of Object.entries(members)) {
    photos[era].cards[code] = files.map(f => {
      if (!cardUrls[f]) throw new Error(`no image info for ${f}`);
      return cardUrls[f];
    });
  }
}

await writeFile(
  OUT,
  `// Generated by scripts/fetch-lesserafim.mjs on ${new Date().toISOString().slice(0, 10)}. Don't edit by hand.\n` +
    `// Photo URLs on the K-pop fandom wiki's CDN, cropped to card shape. Member lists are\n` +
    `// [album PC, selfie PC, POB, lucky draw]; GRP is the group special.\n\n` +
    `export const LESSERAFIM_PHOTOS = ${JSON.stringify(photos, null, 2).replace(/"(\w+)":/g, '$1:').replace(/"/g, "'")};\n`
);
console.log(`Wrote ${cardFiles.length} card photos and ${Object.keys(ERAS).length} covers to lib/photos/lesserafim.js`);
